package render

import (
	"strings"
	"testing"

	"github.com/overspend1/wgh/internal/state"
)

// Fixed, obviously fake keys so the expected output is stable.
const (
	srvPriv = "SERVERPRIVATEKEYAAAAAAAAAAAAAAAAAAAAAAAAAAA="
	srvPub  = "SERVERPUBLICKEYAAAAAAAAAAAAAAAAAAAAAAAAAAAA="
	ph1Priv = "PHONEPRIVATEKEYAAAAAAAAAAAAAAAAAAAAAAAAAAAA="
	ph1Pub  = "PHONEPUBLICKEYAAAAAAAAAAAAAAAAAAAAAAAAAAAAA="
	ph1PSK  = "PHONEPRESHAREDKEYAAAAAAAAAAAAAAAAAAAAAAAAAA="
	lapPriv = "LAPTOPPRIVATEKEYAAAAAAAAAAAAAAAAAAAAAAAAAAA="
	lapPub  = "LAPTOPPUBLICKEYAAAAAAAAAAAAAAAAAAAAAAAAAAAA="
)

func fixture() *state.State {
	return &state.State{
		Version: state.Version,
		Server: state.Server{
			Interface:  "wg0",
			Subnet:     "10.8.0.0/24",
			Address:    "10.8.0.1",
			ListenPort: 51820,
			Endpoint:   "vpn.example.com",
			PrivateKey: srvPriv,
			PublicKey:  srvPub,
			DNS:        []string{"10.8.0.1"},
		},
		Peers: []state.Peer{
			{
				Name: "phone", Address: "10.8.0.2",
				PrivateKey: ph1Priv, PublicKey: ph1Pub, PresharedKey: ph1PSK,
				AllowedIPs: []string{"0.0.0.0/0", "::/0"}, Keepalive: 25,
			},
			{
				Name: "laptop", Address: "10.8.0.3",
				PrivateKey: lapPriv, PublicKey: lapPub,
				AllowedIPs: []string{"10.8.0.0/24", "192.168.1.0/24"},
				DNS:        []string{"192.168.1.53", "9.9.9.9"},
			},
		},
	}
}

func TestServerConfig(t *testing.T) {
	got, err := Server(fixture())
	if err != nil {
		t.Fatal(err)
	}
	want := `# Generated by wgh. Edits are overwritten on the next export.
[Interface]
Address = 10.8.0.1/24
ListenPort = 51820
PrivateKey = ` + srvPriv + `

# phone
[Peer]
PublicKey = ` + ph1Pub + `
PresharedKey = ` + ph1PSK + `
AllowedIPs = 10.8.0.2/32

# laptop
[Peer]
PublicKey = ` + lapPub + `
AllowedIPs = 10.8.0.3/32
`
	if got != want {
		t.Fatalf("server config mismatch\n--- got\n%s\n--- want\n%s", got, want)
	}
}

func TestServerConfigNATAndMTU(t *testing.T) {
	s := fixture()
	s.Server.NATInterface = "eth0"
	s.Server.MTU = 1420
	got, err := Server(s)
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range []string{
		"MTU = 1420\n",
		"PostUp = iptables -A FORWARD -i %i -j ACCEPT; iptables -A FORWARD -o %i -j ACCEPT; iptables -t nat -A POSTROUTING -o eth0 -j MASQUERADE\n",
		"PostDown = iptables -D FORWARD -i %i -j ACCEPT; iptables -D FORWARD -o %i -j ACCEPT; iptables -t nat -D POSTROUTING -o eth0 -j MASQUERADE\n",
	} {
		if !strings.Contains(got, line) {
			t.Errorf("server config missing %q\n%s", line, got)
		}
	}
}

