func TestEndpoint(t *testing.T) {
	cases := []struct {
		in   string
		port int
		want string
	}{
		{"vpn.example.com", 51820, "vpn.example.com:51820"},
		{"vpn.example.com:443", 51820, "vpn.example.com:443"},
		{"203.0.113.7", 51820, "203.0.113.7:51820"},
		{"2001:db8::1", 51820, "[2001:db8::1]:51820"},
		{"[2001:db8::1]", 51820, "[2001:db8::1]:51820"},
		{"[2001:db8::1]:4500", 51820, "[2001:db8::1]:4500"},
	}
	for _, c := range cases {
		if got := Endpoint(c.in, c.port); got != c.want {
			t.Errorf("Endpoint(%q, %d) = %q, want %q", c.in, c.port, got, c.want)
		}
	}
}

func TestSplitList(t *testing.T) {
	got := SplitList(" 0.0.0.0/0, ::/0 ,, ")
	if strings.Join(got, "|") != "0.0.0.0/0|::/0" {
		t.Fatalf("SplitList = %q", got)
	}
	if SplitList("") != nil {
		t.Fatal("SplitList(\"\") should be nil")
	}
}
