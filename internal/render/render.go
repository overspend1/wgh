// Package render turns state into wg-quick style .conf files.
package render

import (
	"fmt"
	"net"
	"net/netip"
	"strconv"
	"strings"

	"github.com/overspend1/wgh/internal/state"
)

// Server renders the server's wg-quick config (e.g. /etc/wireguard/wg0.conf).
func Server(s *state.State) (string, error) {
	prefix, err := s.Subnet()
	if err != nil {
		return "", fmt.Errorf("server subnet: %w", err)
	}
	var b strings.Builder
	b.WriteString("# Generated by wgh. Edits are overwritten on the next export.\n")
	b.WriteString("[Interface]\n")
	fmt.Fprintf(&b, "Address = %s/%d\n", s.Server.Address, prefix.Bits())
	fmt.Fprintf(&b, "ListenPort = %d\n", s.Server.ListenPort)
	fmt.Fprintf(&b, "PrivateKey = %s\n", s.Server.PrivateKey)
	if s.Server.MTU > 0 {
		fmt.Fprintf(&b, "MTU = %d\n", s.Server.MTU)
	}
	if nat := s.Server.NATInterface; nat != "" {
		// %i is expanded by wg-quick to the interface name.
		fmt.Fprintf(&b, "PostUp = iptables -A FORWARD -i %%i -j ACCEPT; iptables -A FORWARD -o %%i -j ACCEPT; iptables -t nat -A POSTROUTING -o %s -j MASQUERADE\n", nat)
		fmt.Fprintf(&b, "PostDown = iptables -D FORWARD -i %%i -j ACCEPT; iptables -D FORWARD -o %%i -j ACCEPT; iptables -t nat -D POSTROUTING -o %s -j MASQUERADE\n", nat)
	}
	for _, p := range s.Peers {
		b.WriteString("\n")
		fmt.Fprintf(&b, "# %s\n", p.Name)
		b.WriteString("[Peer]\n")
		fmt.Fprintf(&b, "PublicKey = %s\n", p.PublicKey)
		if p.PresharedKey != "" {
			fmt.Fprintf(&b, "PresharedKey = %s\n", p.PresharedKey)
		}
		fmt.Fprintf(&b, "AllowedIPs = %s/32\n", p.Address)
	}
	return b.String(), nil
}

// Client renders one peer's config, ready for wg-quick or the mobile apps.
func Client(s *state.State, p *state.Peer) (string, error) {
	prefix, err := s.Subnet()
	if err != nil {
		return "", fmt.Errorf("server subnet: %w", err)
	}
	if s.Server.Endpoint == "" {
		return "", fmt.Errorf("server endpoint is empty")
	}
	var b strings.Builder
	b.WriteString("[Interface]\n")
	fmt.Fprintf(&b, "# Name = %s\n", p.Name)
	fmt.Fprintf(&b, "Address = %s/%d\n", p.Address, prefix.Bits())
	fmt.Fprintf(&b, "PrivateKey = %s\n", p.PrivateKey)
	dns := p.DNS
	if len(dns) == 0 {
		dns = s.Server.DNS
	}
	if len(dns) > 0 {
		fmt.Fprintf(&b, "DNS = %s\n", strings.Join(dns, ", "))
	}
	if s.Server.MTU > 0 {
		fmt.Fprintf(&b, "MTU = %d\n", s.Server.MTU)
	}
	b.WriteString("\n[Peer]\n")
	fmt.Fprintf(&b, "PublicKey = %s\n", s.Server.PublicKey)
	if p.PresharedKey != "" {
		fmt.Fprintf(&b, "PresharedKey = %s\n", p.PresharedKey)
	}
	fmt.Fprintf(&b, "Endpoint = %s\n", Endpoint(s.Server.Endpoint, s.Server.ListenPort))
	fmt.Fprintf(&b, "AllowedIPs = %s\n", strings.Join(p.AllowedIPs, ", "))
	if p.Keepalive > 0 {
		fmt.Fprintf(&b, "PersistentKeepalive = %d\n", p.Keepalive)
	}
	return b.String(), nil
}

// Endpoint returns host:port, adding the listen port when the endpoint has
// none and bracketing bare IPv6 literals.
func Endpoint(endpoint string, port int) string {
	if _, _, err := net.SplitHostPort(endpoint); err == nil {
		return endpoint
	}
	host := strings.TrimSuffix(strings.TrimPrefix(endpoint, "["), "]")
	return net.JoinHostPort(host, strconv.Itoa(port))
}

// SplitList splits a comma-separated flag value, trimming spaces and
// dropping empty items.
func SplitList(v string) []string {
	var out []string
	for _, item := range strings.Split(v, ",") {
		if item = strings.TrimSpace(item); item != "" {
			out = append(out, item)
		}
	}
	return out
}

// ValidateCIDRs checks that every entry is an IP prefix such as 10.8.0.0/24.
func ValidateCIDRs(list []string) error {
	for _, c := range list {
		if _, err := netip.ParsePrefix(c); err != nil {
			return fmt.Errorf("allowed IP %q: %w", c, err)
		}
	}
	return nil
}

// ValidateIPs checks that every entry is a bare IP address.
func ValidateIPs(list []string) error {
	for _, a := range list {
		if _, err := netip.ParseAddr(a); err != nil {
			return fmt.Errorf("address %q: %w", a, err)
		}
	}
	return nil
}
